/// Where the proxy child's pid is recorded, per interface.
fn pid_path(interface: &str) -> PathBuf {
    PathBuf::from("/run/vallum").join(format!("{interface}.dns-proxy.pid"))
}

/// Whether `/proc/<pid>` names a vallum-quick dns-proxy process.
///
/// A pid is reused by the kernel without ceremony, so killing what a stale
/// pidfile names would be killing whoever owns the pid now. The child's argv
/// is the identity: this binary's path plus the `dns-proxy` subcommand.
fn pid_is_ours(pid: u32, exe: &Path) -> bool {
    let cmdline = fs::read_to_string(format!("/proc/{pid}/cmdline")).unwrap_or_default();
    cmdline.split('\0').any(|arg| Path::new(arg) == exe)
        && cmdline.split('\0').any(|arg| arg == "dns-proxy")
}

/// Read the recorded pid, if that process is still a vallum-quick dns-proxy.
fn live_proxy_pid(interface: &str) -> Option<u32> {
    let raw = fs::read_to_string(pid_path(interface)).ok()?;
    let pid: u32 = raw.trim().parse().ok()?;
    let exe = std::env::current_exe().ok()?;
    pid_is_ours(pid, &exe).then_some(pid)
}

/// Spawn the loopback DNS proxy as this process's child and record its pid.
///
/// The child stays in the caller's systemd cgroup, so `systemctl stop` kills it
/// even if the pidfile is unreadable; the pidfile covers the explicit
/// `detach`/`down` paths. Returns an error when the child dies at startup
/// (usually port 53 already taken by another resolver) so the attach can undo.
pub(crate) fn spawn_for_attach(
    config_path: &Path,
    interface: &str,
    control: &Path,
    dry_run: bool,
) -> Result<(), Box<dyn std::error::Error>> {
    if live_proxy_pid(interface).is_some() {
        return Ok(()); // a previous attach already holds the port
    }
    let exe = std::env::current_exe().map_err(|error| format!("find own binary: {error}"))?;
    if dry_run {
        println!(
            "{} dns-proxy --config {} --listen 127.0.0.1:53 --follow-session {}",
            exe.display(),
            config_path.display(),
            control.display()
        );
        return Ok(());
    }
    let mut child = Command::new(&exe)
        .args(["dns-proxy", "--config"])
        .arg(config_path)
        .args(["--listen", "127.0.0.1:53", "--follow-session"])
        .arg(control)
        .spawn()
        .map_err(|error| format!("spawn {}: {error}", exe.display()))?;
    // Binding happens milliseconds after exec; a child that survives this
    // window owns the port. A pidfile naming a dead child would make detach
    // a silent no-op, so the early exit is the failure.
    thread::sleep(Duration::from_millis(300));
    if let Some(status) = child.try_wait()? {
        return Err(format!(
            "the DNS proxy exited at startup ({status}); is another resolver bound to 127.0.0.1:53?"
        )
        .into());
    }
    let pid_path = pid_path(interface);
    if let Some(parent) = pid_path.parent() {
        fs::create_dir_all(parent)
            .map_err(|error| format!("create {}: {error}", parent.display()))?;
    }
    fs::write(&pid_path, format!("{}\n", child.id()))
        .map_err(|error| format!("write {}: {error}", pid_path.display()))?;
    Ok(())
}

/// Kill the proxy a previous attach left behind, and clear the pidfile.
/// A missing or stale pidfile is a no-op: teardown must not fail because
/// there was nothing to tear down.
pub(crate) fn stop_for_detach(interface: &str, dry_run: bool) {
    let Some(pid) = live_proxy_pid(interface) else {
        if !dry_run {
            let _ = fs::remove_file(pid_path(interface));
        }
        return;
    };
    if dry_run {
        println!(
            "would kill dns-proxy pid {pid} and remove {}",
            pid_path(interface).display()
        );
        return;
    }
    // SIGTERM, not SIGKILL: Drop answers in-flight queries with the shutdown
    // path and joins the dispatch loop, so the port is free immediately.
    let _ = Command::new("kill")
        .args(["-TERM", &pid.to_string()])
        .status();
    let _ = fs::remove_file(pid_path(interface));
}

#[cfg(test)]
mod lifecycle_tests {
    #![allow(clippy::expect_used, clippy::unwrap_used)]
    use super::*;
    use crate::watch::DEAD_AFTER;

    #[test]
    fn a_pid_without_the_dns_proxy_argv_is_not_ours() {
        // This test process's own cmdline names the test harness, not the
        // `dns-proxy` subcommand, so a pidfile naming it must be rejected —
        // that is exactly the stale-pid case teardown has to survive.
        let exe = std::env::current_exe().expect("own exe");
        assert!(!pid_is_ours(std::process::id(), &exe));
    }

    #[test]
    fn a_dead_session_within_the_watchdog_window_is_not_blocked() {
        let live = Some(Duration::from_secs(60));
        let dead = Some(DEAD_AFTER + Duration::from_secs(30));
        assert!(!captive_spoof_from_health(live, DEAD_AFTER));
        assert!(captive_spoof_from_health(dead, DEAD_AFTER));
        // No handshake at all: the blocked state the spoof exists to answer.
        assert!(captive_spoof_from_health(None, DEAD_AFTER));
    }
}
